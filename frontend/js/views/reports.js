/* Reports — generate + list + download JSON reports, CSV export. */
NT.views.reports = async function (root) {
  root.innerHTML = `
    <div class="view-head"><h2>Reports</h2>
    <p>Generate structured analysis reports (JSON) and export the entity catalog as CSV for downstream tooling.</p></div>
    <div class="grid grid-2">
      ${NT.card('Generate report', `
        <div class="col">
          <input id="rp-title" type="text" placeholder="Report title" value="NetworkTrace Analysis Report">
          <div class="row" style="flex-wrap:wrap">
            <label><input type="checkbox" class="rp-sec" value="summary" checked> Summary</label>
            <label><input type="checkbox" class="rp-sec" value="entities" checked> Top entities</label>
            <label><input type="checkbox" class="rp-sec" value="graph" checked> Graph metrics</label>
            <label><input type="checkbox" class="rp-sec" value="anomalies" checked> Anomalies</label>
          </div>
          <button id="rp-gen" class="btn btn-primary btn-sm">Generate report</button>
        </div>`)}
      ${NT.card('CSV export', `
        <p class="muted">Export the full entity catalog as a CSV file.</p>
        <button id="rp-csv" class="btn btn-sm">Export entities.csv</button>`)}
    </div>
    <div class="section-title">Generated reports</div>
    <div id="rp-list">${NT.loading()}</div>`;

  const load = async () => {
    const data = await NT.api('/api/reports');
    document.getElementById('rp-list').innerHTML = NT.table(
      [{ label: 'Report ID', render: r => `<span class="mono">${NT.esc(r.id)}</span>` },
       { label: 'Title', key: 'title' },
       { label: 'Generated by', key: 'generated_by' },
       { label: 'Size', render: r => `${(r.size / 1024).toFixed(1)} KB`, num: true },
       { label: '', render: r => `<a class="btn btn-sm" href="/api/reports/${r.id}/download" target="_blank">Download</a>` }],
      data.items);
  };
  document.getElementById('rp-gen').addEventListener('click', async () => {
    const sections = [...document.querySelectorAll('.rp-sec:checked')].map(c => c.value);
    const title = document.getElementById('rp-title').value || 'Report';
    try { const r = await NT.api('/api/reports/generate', { method: 'POST', body: { title, sections } });
      NT.toast('Report ' + r.id + ' generated', 'success'); load(); }
    catch (e) { NT.toast(e.message, 'error'); }
  });
  document.getElementById('rp-csv').addEventListener('click', () => {
    window.open('/api/reports/export/entities', '_blank');
  });
  await load();
};
